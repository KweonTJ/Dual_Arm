"""ROS-independent AX-12A control API. One lock serializes all bus operations.

Position control uses the servo's onboard controller. This is not a hard real
time loop or a current/torque command interface. N.m is never sent to AX-12A.
"""
from copy import deepcopy
import math
from pathlib import Path
import sys
import threading
import time

import yaml
from ax12_guard import ProtectedArm, ProtectionError, SDKBus, load_configuration
from hardware_telemetry import read_telemetry

DEFAULTS = dict(control_hz=20.,protection_check_hz=2.,command_timeout_s=1.,feedback_timeout_s=.5)


def loop_settings(values=None):
    result = {**DEFAULTS,**(values or {})}
    if set(result) != set(DEFAULTS) or any(type(v) not in (int,float) or not math.isfinite(v) or v<=0
                                         for v in result.values()):
        raise ProtectionError('Low-level settings must be known, finite, positive numbers')
    if result['control_hz']>100 or result['protection_check_hz']>result['control_hz']:
        raise ProtectionError('Use control_hz <= 100 and protection_check_hz <= control_hz')
    if result['command_timeout_s'] < 2/result['control_hz']:
        raise ProtectionError('Command timeout must span at least two control cycles')
    return result


class DualArmLowLevel:
    def __init__(self,bus,motors,description_config,settings=None,clock=time.monotonic):
        self.settings = loop_settings(settings)
        self.bus,self.arm,self.clock = bus,ProtectedArm(bus,motors),clock
        self.names = tuple(m.joint for m in motors)
        self.by_name = {m.joint:m for m in motors}
        sys.path.insert(0,str(Path(description_config).parent/'scripts'))
        from gripper_kinematics import absolute_angle,START,CLOSED,expand_positions
        self._angle,self._start_angle,self._closed,self._expand = absolute_angle,START,CLOSED,expand_positions
        self._lock = threading.RLock()
        self._quit = threading.Event()
        self._thread = None
        self._started = self._closed_port = False
        self._samples,self._targets,self._raw_goals = {},{},{}
        self._sampled_at = self._lease_at = None
        self._verify_at = 0.
        self.fault_message = ''
        self.stats = dict(cycles=0,overruns=0,last_cycle_s=0.,max_cycle_s=0.)

    @classmethod
    def from_config(cls,hardware_config,description_config,loop_config=None):
        # All validation and module imports precede the first serial operation.
        config,motors = load_configuration(hardware_config,description_config)
        values = yaml.safe_load(Path(loop_config).read_text()) if loop_config else None
        settings = loop_settings(values)
        # Construct without opening the bus first so missing kinematics cannot leak a port.
        instance = cls(None,motors,description_config,settings)
        instance.bus = instance.arm.bus = SDKBus(config['port'],config['baudrate'])
        return instance

    def start(self,background=True):
        with self._lock:
            if self._started or self._closed_port:
                raise ProtectionError('Session already started/closed')
            try:
                self.arm.prepare(apply=True)
                self._started = True
                self.poll()
                if self.arm.fault:
                    raise ProtectionError(self.fault_message)
            except Exception:
                # A failed read-only preflight may find already-enabled motors.
                # Do not take ownership and disable another existing session.
                if self.arm.fault:
                    self.arm.stop(fault=True)
                self.bus.close();self._closed_port=True
                raise
        if background:
            self._thread = threading.Thread(target=self._run,name='dual-arm-bus',daemon=True)
            self._thread.start()
        return self

    def _available(self):
        if not self._started or self._closed_port:
            raise ProtectionError('Start an open session first')
        if self.arm.fault:
            raise ProtectionError('Latched fault; restart session: '+self.fault_message)

    def _trip(self,reason):
        if self.arm.fault and self.fault_message:
            return
        self.fault_message = str(reason)
        self._samples = {}
        self.arm.stop(fault=True)

    def _lease(self):
        if self.arm.enabled and self.clock()-self._lease_at >= self.settings['command_timeout_s']:
            self._trip('Command/keepalive timeout')
            raise ProtectionError(self.fault_message)

    def keepalive(self):
        """Client liveness, never generated by the bus worker itself."""
        with self._lock:
            self._available();self._lease()
            if self.arm.enabled:self._lease_at=self.clock()

    def enable(self):
        with self._lock:
            self._available()
            if self.arm.enabled:
                raise ProtectionError('Torque already enabled')
            try:
                self.arm.enable()  # Writes measured positions before enabling any motor.
                self._lease_at=self.clock()
                self._samples=read_telemetry(self.arm)
                self._sampled_at=self.clock()
                self._targets={n:s['position_rad'] for n,s in self._samples.items()}
                self._raw_goals={s['motor_id']:s['goal_raw'] for s in self._samples.values()}
                self._lease()
            except Exception as exc:
                self._trip(exc);raise
            return self.snapshot()

    def disable(self):
        with self._lock:
            if self._closed_port:return []
            errors=self.arm.stop()
            self._samples={}
            if errors:
                self.arm.fault=True;self.fault_message='Torque OFF unconfirmed: '+'; '.join(errors)
            return list(errors)

    def emergency_stop(self,reason='Emergency stop requested'):
        with self._lock:
            if not self._closed_port:self._trip(reason)
            return list(self.arm.stop_errors)

    def set_positions(self,targets,require_all=False):
        """Radians relative to motor zero 180 deg; subset commands hold other goals.

        Entire batch validated before transmission. Sync Write is followed by
        per-device Goal Position readback; failure stops and latches the session.
        """
        with self._lock:
            self._available();self._lease()
            if not isinstance(targets,dict) or not targets or not set(targets)<=set(self.names):
                raise ProtectionError('Supply a nonempty mapping of known motor joints')
            if require_all and set(targets)!=set(self.names):
                raise ProtectionError('Supply all ten motor targets')
            if any(type(v) not in (int,float) or not math.isfinite(v) for v in targets.values()):
                raise ProtectionError('Targets must be finite radians')
            merged={**self._targets,**targets}
            raw=self.arm.validate_targets(list(merged),list(merged.values()))
            try:
                self.arm.verify(enabled=True)
                self._lease()  # A slow bus must not revive an expired command.
                self.bus.sync_write_positions(raw)
                started=self.clock()
                samples=read_telemetry(self.arm)
                for name,sample in samples.items():
                    if sample['goal_raw']!=raw[sample['motor_id']]:
                        raise ProtectionError(f'{name}: Sync Write goal readback differs')
                if self.clock()-started>self.settings['feedback_timeout_s']:
                    raise ProtectionError('Command readback exceeded feedback timeout')
                self._lease()
                self._samples=samples;self._sampled_at=self.clock()
                self._targets=merged;self._raw_goals=raw;self._lease_at=self.clock()
            except Exception as exc:
                self._trip(exc);raise
            return self.snapshot()

    def set_gripper(self,side,opening_mm):
        if side not in ('left','right') or type(opening_mm) not in (int,float) or not math.isfinite(opening_mm) or not 0<=opening_mm<=70:
            raise ProtectionError('Gripper requires left/right and an opening in 0..70 mm')
        angle=self._angle(self._closed+opening_mm/2000)-self._start_angle
        return self.set_positions({side+'_gripper_joint':angle})

    def hold(self):
        """Replace targets with fresh measured positions while keeping torque ON."""
        with self._lock:
            self._available();self._lease()
            if not self.arm.enabled:raise ProtectionError('Enable before requesting hold')
            try:
                began=self.clock();samples=read_telemetry(self.arm)
                if self.clock()-began>self.settings['feedback_timeout_s']:
                    raise ProtectionError('Hold measurement exceeded feedback timeout')
                self._lease()
            except Exception as exc:
                self._trip(exc);raise
            return self.set_positions({n:s['position_rad'] for n,s in samples.items()},require_all=True)

    def poll(self):
        with self._lock:
            self._available()
            began=self.clock()
            try:
                self._lease()
                if began>=self._verify_at:
                    self.arm.verify(enabled=self.arm.enabled)
                    self._verify_at=self.clock()+1/self.settings['protection_check_hz']
                samples=read_telemetry(self.arm)
                if self.arm.enabled:
                    for sample in samples.values():
                        if sample['goal_raw']!=self._raw_goals[sample['motor_id']]:
                            raise ProtectionError('Goal Position changed outside this session')
                elapsed=self.clock()-began
                if elapsed>self.settings['feedback_timeout_s']:
                    raise ProtectionError('Bus scan exceeded feedback timeout')
                self._lease()
                self._samples=samples;self._sampled_at=self.clock()
                self.stats['cycles']+=1;self.stats['last_cycle_s']=elapsed
                self.stats['max_cycle_s']=max(self.stats['max_cycle_s'],elapsed)
                self.stats['overruns']+=int(elapsed>1/self.settings['control_hz'])
            except Exception as exc:
                self._trip(exc);raise
            return self.snapshot()

    def snapshot(self):
        with self._lock:
            age=None if self._sampled_at is None else max(0,self.clock()-self._sampled_at)
            valid=bool(self._samples) and not self.arm.fault and not self._closed_port and age<=self.settings['feedback_timeout_s']
            samples=deepcopy(self._samples) if valid else {}
            return dict(state='CLOSED' if self._closed_port else 'FAULT' if self.arm.fault else
                        'RUNNING' if self.arm.enabled else 'TORQUE_OFF',sample_valid=valid,
                        sample_age_s=age,samples=samples,targets_rad=dict(self._targets),
                        joint_positions_rad=self._expand({n:s['position_rad'] for n,s in samples.items()}),
                        fault=self.fault_message,torque_off_unconfirmed=list(self.arm.stop_errors),
                        stats=dict(self.stats))

    def _run(self):
        while not self._quit.is_set():
            began=self.clock()
            try:self.poll()
            except Exception:
                # Fault stays latched; no automatic restart, recovery or device writes.
                return
            self._quit.wait(max(0,1/self.settings['control_hz']-(self.clock()-began)))

    def close(self):
        self._quit.set()
        if self._thread is not None and self._thread is not threading.current_thread():
            self._thread.join()
        with self._lock:
            if self._closed_port:return list(self.arm.stop_errors)
            errors=self.disable() if self._started else []
            try:self.bus.close()
            finally:self._closed_port=True
            return errors

    def __enter__(self):return self.start()
    def __exit__(self,exc_type,exc_value,traceback):
        errors=self.close()
        if errors:
            raise ProtectionError('Torque OFF unconfirmed: '+'; '.join(errors)) from exc_value
